CTRY = {"United States": "USA", "United Kingdom": "UK", "United Arab Emirates": "UAE", "China / United States": "China, USA",
        "Unknown": "--"}

def esc(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%")

def inst(s):
    s = INST.get(s, s)
    return s if s.startswith("\\") or "\\\"" in s else esc(s)

def institutions(team):                                          # cleaned, split into single institutions, de-duplicated
    out = []
    for s in affils[team]:
        for p in inst(s).split(", "):
            if p and p not in out: out.append(p)
    return ", ".join(out) or "--"

lines = []
for r in rows:
    t = r["team"]; lo, hi = ci[t]
    lines.append(f"Team {r['rank']} & {institutions(t)} & {CTRY.get(country[t], country[t])} & "
                 f"{float(r['dice_full_test']):.4f} & {lo:.3f}--{hi:.3f} & {float(r['hit_rate']):.4f} & "
                 f"{float(r['instance_f1']):.4f} & {r['n_submissions']} \\\\")
    if r["rank"] in ("4", "10"):
        lines.append("\\midrule")

