for e in json.load(open("final_results_MICCAI2026.json"))["results"]:
    a = affils.setdefault(MERGED.get(e["team"], e["team"]), [])
    for s in [e["institution"]] + [m.get("affiliation") or "" for m in e.get("members") or []]:
        if s.strip() and s.strip() not in a: a.append(s.strip())

